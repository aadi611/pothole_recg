#!/usr/bin/env python
"""Train the pothole detector (FR-DET-02).

Non-interactive. Records mAP@50 and mAP@50-95 plus the weights hash into
``docs/MODEL_CARD.md`` so every trained model is traceable (FR-DET-06,
NFR-DEV-06).

Usage:
    python scripts/train_detector.py --data datasets/roboflow-pothole/data.yaml
    python scripts/train_detector.py --data ... --epochs 100 --model yolov8s.pt
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / "models"
DOCS = ROOT / "docs"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        while chunk := fh.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def _write_model_card(
    *,
    weights: Path,
    digest: str,
    metrics: dict[str, float],
    dataset: Path,
    epochs: int,
    base_model: str,
    imgsz: int,
    device: str,
    duration_min: float,
) -> None:
    """Record what was trained, on what, and how well it did.

    Honest reporting matters here: these numbers decide whether the system is
    trustworthy enough to file civic complaints, so limitations are stated
    alongside the metrics rather than left implied.
    """
    DOCS.mkdir(parents=True, exist_ok=True)
    card = DOCS / "MODEL_CARD.md"

    map50 = metrics.get("metrics/mAP50(B)", 0.0)
    map5095 = metrics.get("metrics/mAP50-95(B)", 0.0)
    precision = metrics.get("metrics/precision(B)", 0.0)
    recall = metrics.get("metrics/recall(B)", 0.0)

    content = f"""# Model Card — pothole detector

Generated by `scripts/train_detector.py`. Do not edit by hand; retrain to update.

## Identity

| | |
|---|---|
| **Weights** | `{weights.name}` |
| **SHA-256** | `{digest}` |
| **model_version** | `yolo-{digest[:12]}` |
| **Trained** | {datetime.now(UTC).isoformat(timespec="seconds")} |

The `model_version` stamped on every detection and report derives from this
hash (FR-DET-06). Put the SHA-256 into `config/detection.yaml` as
`model.weights_sha256` so a swapped weights file fails loudly at startup
instead of silently changing behaviour.

## Training

| | |
|---|---|
| Base model | `{base_model}` |
| Dataset | `{dataset}` |
| Epochs | {epochs} |
| Image size | {imgsz} |
| Device | {device} |
| Duration | {duration_min:.1f} min |

## Metrics (validation split)

| Metric | Value |
|---|---|
| mAP@50 | **{map50:.3f}** |
| mAP@50-95 | **{map5095:.3f}** |
| Precision | {precision:.3f} |
| Recall | {recall:.3f} |

mAP@50-95 is the honest number; mAP@50 flatters a detector that localises
loosely. For this application loose localisation matters directly: the bottom
edge of the box is the ground-contact point that distance estimation projects
(FR-PRX-02), so a box that is right-ish but low reads as a pothole that is
closer than it is.

## Known limitations

- **Domain gap.** Trained predominantly on non-Indian road imagery. Indian
  roads differ in surface texture, repair patterns, edge degradation, and
  unsealed shoulders. Expect degraded recall until retrained on the RDD2022
  India subset (see `docs/DATASETS.md`).
- **Water and shadow.** A pothole filled with water or in deep shadow is
  frequently missed or mis-sized. This directly affects severity, which is
  derived from apparent area.
- **Single class.** Only `pothole` is active. Cracks and surface damage are
  defined in the class map but not trained (FR-DET-03).
- **No night-time validation.** The training data is predominantly daylight.

These are limitations of the model, not of the pipeline. Report them; do not
work around them silently.
"""
    card.write_text(content, encoding="utf-8")
    print(f"Wrote {card}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True, help="Path to YOLO data.yaml")
    parser.add_argument("--model", default="yolov8n.pt", help="Base weights")
    parser.add_argument("--epochs", type=int, default=80)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", type=int, default=16)
    parser.add_argument("--device", default="0", help="'0' for first CUDA device, 'cpu'")
    parser.add_argument("--name", default="pothole", help="Run name")
    args = parser.parse_args()

    data = Path(args.data)
    if not data.is_file():
        print(f"error: data.yaml not found: {data}", file=sys.stderr)
        print("Fetch a dataset first: python scripts/fetch_dataset.py", file=sys.stderr)
        return 1

    try:
        from ultralytics import YOLO
    except ImportError:
        print(
            'error: ultralytics not installed. Run: pip install -e ".[training]"',
            file=sys.stderr,
        )
        return 1

    print(f"Training {args.model} on {data} for {args.epochs} epochs (device {args.device})")
    started = datetime.now(UTC)

    model = YOLO(args.model)
    model.train(
        data=str(data),
        epochs=args.epochs,
        imgsz=args.imgsz,
        batch=args.batch,
        device=args.device,
        name=args.name,
        project=str(ROOT / "runs"),
        exist_ok=True,
        patience=20,
    )

    metrics_obj = model.val(data=str(data), device=args.device, verbose=False)
    metrics = dict(getattr(metrics_obj, "results_dict", {}))

    duration_min = (datetime.now(UTC) - started).total_seconds() / 60

    best = ROOT / "runs" / args.name / "weights" / "best.pt"
    if not best.is_file():
        print(f"error: expected trained weights at {best}", file=sys.stderr)
        return 1

    MODELS.mkdir(parents=True, exist_ok=True)
    final = MODELS / f"pothole-{Path(args.model).stem}.pt"
    shutil.copy2(best, final)

    digest = _sha256(final)

    _write_model_card(
        weights=final,
        digest=digest,
        metrics=metrics,
        dataset=data,
        epochs=args.epochs,
        base_model=args.model,
        imgsz=args.imgsz,
        device=args.device,
        duration_min=duration_min,
    )

    (MODELS / f"{final.stem}.json").write_text(
        json.dumps(
            {
                "weights": final.name,
                "sha256": digest,
                "model_version": f"yolo-{digest[:12]}",
                "metrics": metrics,
                "trained_at": datetime.now(UTC).isoformat(),
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    print(f"\nWeights: {final}")
    print(f"SHA-256: {digest}")
    print(f"mAP@50:    {metrics.get('metrics/mAP50(B)', 0):.3f}")
    print(f"mAP@50-95: {metrics.get('metrics/mAP50-95(B)', 0):.3f}")
    print(
        f"\nSet in config/detection.yaml:\n"
        f"  weights_path: \"models/{final.name}\"\n"
        f"  weights_sha256: \"{digest}\""
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
